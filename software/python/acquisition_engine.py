# SYNTHETIC DATA GENERATOR
# ============================================================================

def generate_synthetic_signal(prn_id: int, true_doppler: float, 
                              true_code_phase: float, num_samples: int,
                              config: ConstellationConfig, 
                              snr_db: float = 10.0) -> Tuple[List[float], List[float]]:
    """
    Generate synthetic GPS signal with known parameters
    
    Args:
        prn_id: PRN satellite ID
        true_doppler: True Doppler frequency in Hz
        true_code_phase: True code phase in chips
        num_samples: Number of samples to generate
        config: Constellation configuration
        snr_db: Signal-to-noise ratio in dB
        
    Returns:
        Tuple of (signal_I, signal_Q)
    """
    prn_code = generate_gps_prn(prn_id)
    
    # Calculate noise standard deviation from SNR
    signal_power = 1.0  # Normalized
    noise_power = signal_power / (10 ** (snr_db / 10))
    noise_std = math.sqrt(noise_power)
    
    signal_I = []
    signal_Q = []
    
    for i in range(num_samples):
        # Carrier phase
        carrier_phase = 2 * math.pi * true_doppler * i / config.sample_rate
        
        # Code phase (with offset and chip rate)
        chip_idx = int((i * config.chip_rate / config.sample_rate) + true_code_phase) % config.code_length
        
        # Signal = PRN * carrier
        sig_I = prn_code[chip_idx] * math.cos(carrier_phase)
        sig_Q = prn_code[chip_idx] * math.sin(carrier_phase)
        
        # Add noise
        sig_I += random.gauss(0, noise_std)
        sig_Q += random.gauss(0, noise_std)
        
        signal_I.append(sig_I)
        signal_Q.append(sig_Q)
    
    return signal_I, signal_Q

