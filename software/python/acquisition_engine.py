@dataclass
class AcquisitionResult:
    """Result of acquisition search"""
    prn_id: int
    doppler_hz: float
    code_phase_chips: float
    peak_power: float
    noise_floor: float
    pnr: float  # Peak-to-noise ratio
    acquired: bool
    corr_results: Dict  # E/P/L correlator outputs at peak
    exec_time_us: float

class AcquisitionEngine:
    """2D Acquisition Search Engine"""
    
    def __init__(self, hw: EnhancedCorrelatorHW, config: ConstellationConfig):
        self.hw = hw
        self.config = config
        
    def search(self, signal_I: List[float], signal_Q: List[float], 
               prn_id: int, progress_callback=None) -> AcquisitionResult:
        """
        Perform 2D search (Doppler × Code Phase)
        
        Args:
            signal_I: I channel samples
            signal_Q: Q channel samples
            prn_id: PRN satellite ID (1-32 for GPS)
            progress_callback: Optional callback(percent_complete, current_doppler)
            
        Returns:
            AcquisitionResult with best peak found
        """
        print(f"\n🛰️  Acquiring PRN {prn_id}...")
        
        # Generate PRN code
        prn_code = generate_gps_prn(prn_id)
        
        # Calculate number of samples (1 ms of data for GPS L1 C/A)
        num_samples = int(self.config.sample_rate * self.config.integration_time_ms / 1000)
        num_samples = min(num_samples, len(signal_I))
        
        # Truncate signals to num_samples
        signal_I = signal_I[:num_samples]
        signal_Q = signal_Q[:num_samples]
        
        print(f"   Samples: {num_samples}")
        print(f"   Integration time: {self.config.integration_time_ms} ms")
        
        # 2D Search
        doppler_min, doppler_max = self.config.doppler_range
        doppler_step = self.config.doppler_step
        code_step = self.config.code_phase_step
        
        doppler_bins = np.arange(doppler_min, doppler_max + doppler_step, doppler_step)
        code_phases = np.arange(0, self.config.code_length, code_step)
        
        total_cells = len(doppler_bins) * len(code_phases)
        print(f"   Search space: {len(doppler_bins)} Doppler × {len(code_phases)} code = {total_cells} cells")
        
        best_power = 0.0
        best_doppler = 0.0
        best_code_phase = 0.0
        best_result = None
        
        cells_tested = 0
        start_total = time.perf_counter()
        
        for doppler_idx, doppler in enumerate(doppler_bins):
            if progress_callback and doppler_idx % 5 == 0:
                progress_callback(100.0 * doppler_idx / len(doppler_bins), doppler)
            
            for code_phase in code_phases:
                try:
                    result = self.hw.correlate(
                        signal_I, signal_Q, prn_code,
                        float(doppler), float(code_phase), self.config
                    )
                    
                    # Calculate power
                    power = result['P_I']**2 + result['P_Q']**2
                    cells_tested += 1
                    
                    if power > best_power:
                        best_power = power
                        best_doppler = doppler
                        best_code_phase = code_phase
                        best_result = result
                        
                except Exception as e:
                    print(f"   ⚠️  Error at Doppler={doppler}, Code={code_phase}: {e}")
                    continue
        
        total_time = time.perf_counter() - start_total
        
        # Calculate noise floor (average of all powers except the peak)
        # For simplicity, use a rough estimate
        noise_floor = best_power / 10.0  # Rough estimate
        pnr = best_power / noise_floor if noise_floor > 0 else 0.0
        
        # Validate acquisition
        acquired = pnr >= self.config.acq_threshold
        
        return AcquisitionResult(
            prn_id=prn_id,
            doppler_hz=best_doppler,
            code_phase_chips=best_code_phase,
            peak_power=best_power,
            noise_floor=noise_floor,
            pnr=pnr,
            acquired=acquired,
            corr_results=best_result if best_result else {},
            exec_time_us=total_time * 1e6
        )

