# HARDWARE INTERFACE
# ============================================================================

class EnhancedCorrelatorHW:
    """Hardware interface for the enhanced correlator IP"""
    
    def __init__(self, base_address: int, ddr_address: int = 0x1E000000):
        """
        Args:
            base_address: AXI-Lite control base address (from Vivado Address Editor)
            ddr_address: DDR memory base address for data buffers
        """
        self.base_address = base_address
        self.ddr_address = ddr_address
        self.map_size = 256 * 1024  # 256KB mapping
        
        # Register offsets (auto-generated by Vivado HLS)
        self.OFF_AP_CTRL            = 0x00
        self.OFF_SIGNAL_I_LOW       = 0x10
        self.OFF_SIGNAL_I_HIGH      = 0x14
        self.OFF_SIGNAL_Q_LOW       = 0x1C
        self.OFF_SIGNAL_Q_HIGH      = 0x20
        self.OFF_PRN_CODE_LOW       = 0x28
        self.OFF_PRN_CODE_HIGH      = 0x2C
        self.OFF_NUM_SAMPLES        = 0x30
        self.OFF_CARRIER_FREQ       = 0x34
        self.OFF_CARRIER_PHASE_INIT = 0x38
        self.OFF_CODE_PHASE_INIT    = 0x3C
        self.OFF_CODE_FREQ          = 0x40
        self.OFF_SAMPLE_RATE        = 0x44
        self.OFF_CODE_LENGTH        = 0x48
        self.OFF_CORR_SPACING       = 0x4C
        self.OFF_CORR_E_I           = 0x50
        self.OFF_CORR_E_Q           = 0x58
        self.OFF_CORR_P_I           = 0x60
        self.OFF_CORR_P_Q           = 0x68
        self.OFF_CORR_L_I           = 0x70
        self.OFF_CORR_L_Q           = 0x78
        
        # DDR buffer offsets (within our DDR mapping)
        self.DDR_SIGNAL_I_OFFSET = 0x00000
        self.DDR_SIGNAL_Q_OFFSET = 0x10000
        self.DDR_PRN_CODE_OFFSET = 0x20000
        
        self.fd = None
        self.ctrl_mem = None
        self.ddr_mem = None
        
    def open(self):
        """Open memory mappings"""
        self.fd = os.open("/dev/mem", os.O_RDWR | os.O_SYNC)
        self.ctrl_mem = mmap.mmap(
            self.fd, self.map_size, mmap.MAP_SHARED,
            mmap.PROT_READ | mmap.PROT_WRITE, 
            offset=self.base_address
        )
        self.ddr_mem = mmap.mmap(
            self.fd, self.map_size, mmap.MAP_SHARED,
            mmap.PROT_READ | mmap.PROT_WRITE,
            offset=self.ddr_address
        )
        
    def close(self):
        """Close memory mappings"""
        if self.ctrl_mem:
            self.ctrl_mem.close()
        if self.ddr_mem:
            self.ddr_mem.close()
        if self.fd:
            os.close(self.fd)
            
    def write_reg(self, offset: int, value: int):
        """Write 32-bit register"""
        self.ctrl_mem.seek(offset)
        self.ctrl_mem.write(struct.pack('<I', value & 0xFFFFFFFF))
        
    def read_reg(self, offset: int) -> int:
        """Read 32-bit register"""
        self.ctrl_mem.seek(offset)
        return struct.unpack('<I', self.ctrl_mem.read(4))[0]
        
    def write_float(self, offset: int, value: float):
        """Write float register"""
        self.ctrl_mem.seek(offset)
        self.ctrl_mem.write(struct.pack('<f', value))
        
    def read_float(self, offset: int) -> float:
        """Read float register"""
        self.ctrl_mem.seek(offset)
        val_int = struct.unpack('<I', self.ctrl_mem.read(4))[0]
        return struct.unpack('<f', struct.pack('<I', val_int))[0]
        
    def write_float_array(self, offset: int, array: List[float]):
        """Write array of floats to DDR"""
        self.ddr_mem.seek(offset)
        for val in array:
            self.ddr_mem.write(struct.pack('<f', val))
            
    def flush_cache(self):
        """Flush cache to ensure DDR coherency"""
        for i in range(0, self.map_size, 4096):
            self.ddr_mem.seek(i)
            _ = self.ddr_mem.read(4096)
        os.sync()
        
    def correlate(self, signal_I: List[float], signal_Q: List[float], 
                  prn_code: List[float], carrier_freq: float, 
                  code_phase: float, config: ConstellationConfig) -> Dict:
        """
        Run one correlation with the FPGA
        
        Returns dict with E_I, E_Q, P_I, P_Q, L_I, L_Q, exec_time
        """
        num_samples = len(signal_I)
        
        # Write data to DDR
        self.write_float_array(self.DDR_SIGNAL_I_OFFSET, signal_I)
        self.write_float_array(self.DDR_SIGNAL_Q_OFFSET, signal_Q)
        self.write_float_array(self.DDR_PRN_CODE_OFFSET, prn_code)
        self.flush_cache()
        
        # Configure correlator
        self.write_reg(self.OFF_SIGNAL_I_LOW, self.ddr_address + self.DDR_SIGNAL_I_OFFSET)
        self.write_reg(self.OFF_SIGNAL_I_HIGH, 0)
        self.write_reg(self.OFF_SIGNAL_Q_LOW, self.ddr_address + self.DDR_SIGNAL_Q_OFFSET)
        self.write_reg(self.OFF_SIGNAL_Q_HIGH, 0)
        self.write_reg(self.OFF_PRN_CODE_LOW, self.ddr_address + self.DDR_PRN_CODE_OFFSET)
        self.write_reg(self.OFF_PRN_CODE_HIGH, 0)
        
        self.write_reg(self.OFF_NUM_SAMPLES, num_samples)
        self.write_float(self.OFF_CARRIER_FREQ, carrier_freq)
        self.write_float(self.OFF_CARRIER_PHASE_INIT, 0.0)
        self.write_float(self.OFF_CODE_PHASE_INIT, code_phase)
        self.write_float(self.OFF_CODE_FREQ, config.chip_rate)
        self.write_float(self.OFF_SAMPLE_RATE, config.sample_rate)
        self.write_reg(self.OFF_CODE_LENGTH, config.code_length)
        self.write_float(self.OFF_CORR_SPACING, config.correlator_spacing)
        
        # Start correlator
        self.write_reg(self.OFF_AP_CTRL, 0x1)
        
        # Wait for completion
        start = time.perf_counter()
        timeout = 5.0
        while not (self.read_reg(self.OFF_AP_CTRL) & 0x2):
            if time.perf_counter() - start > timeout:
                raise TimeoutError(f"Correlator timeout after {timeout}s")
            time.sleep(0.0001)
            
        exec_time = (time.perf_counter() - start) * 1e6
        
        # Read results
        result = {
            'E_I': self.read_float(self.OFF_CORR_E_I),
            'E_Q': self.read_float(self.OFF_CORR_E_Q),
            'P_I': self.read_float(self.OFF_CORR_P_I),
            'P_Q': self.read_float(self.OFF_CORR_P_Q),
            'L_I': self.read_float(self.OFF_CORR_L_I),
            'L_Q': self.read_float(self.OFF_CORR_L_Q),
            'exec_time': exec_time
        }
        
        return result

# ============================================================================
# GPS PRN CODE GENERATOR
# ============================================================================

def generate_gps_prn(prn_id: int) -> List[float]:
    """Generate GPS L1 C/A PRN code for PRN 1-32"""
    g2_taps = {
        1: [2,6], 2: [3,7], 3: [4,8], 4: [5,9], 5: [1,9],
        6: [2,10], 7: [1,8], 8: [2,9], 9: [3,10], 10: [2,3],
        11: [3,4], 12: [5,6], 13: [6,7], 14: [7,8], 15: [8,9],
        16: [9,10], 17: [1,4], 18: [2,5], 19: [3,6], 20: [4,7],
        21: [5,8], 22: [6,9], 23: [1,3], 24: [4,6], 25: [5,7],
        26: [6,8], 27: [7,9], 28: [8,10], 29: [1,6], 30: [2,7],
        31: [3,8], 32: [4,9]
    }
    
    if prn_id not in g2_taps:
        raise ValueError(f"PRN ID must be 1-32, got {prn_id}")
        
    taps = g2_taps[prn_id]
    g1 = [1] * 10
    g2 = [1] * 10
    code = []
    
    for _ in range(1023):
        output = g1[9] ^ g2[taps[0]-1] ^ g2[taps[1]-1]
        code.append(1.0 if output == 1 else -1.0)
        g1_fb = g1[9] ^ g1[2]
        g2_fb = g2[9] ^ g2[8] ^ g2[7] ^ g2[5] ^ g2[2] ^ g2[1]
        g1 = [g1_fb] + g1[:-1]
        g2 = [g2_fb] + g2[:-1]
    
    return code

